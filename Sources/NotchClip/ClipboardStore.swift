import AppKit
import SwiftUI

@MainActor final class ClipboardStore: ObservableObject {
    @Published private(set) var history: History
    private let pasteboard: NSPasteboard
    private let fileURL: URL
    private var changeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general, fileURL: URL? = nil) {
        self.pasteboard = pasteboard
        let directory = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("NotchClip", isDirectory: true)
        self.fileURL = fileURL ?? directory.appendingPathComponent("history.json")
        self.history = (try? Data(contentsOf: self.fileURL)).flatMap { try? JSONDecoder().decode(History.self, from: $0) } ?? History()
        self.changeCount = pasteboard.changeCount
    }
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }
    func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        // Password managers can mark transient and confidential clipboard contents.
        let types = pasteboard.types ?? []
        let ignored = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"]
        guard !types.contains(where: { ignored.contains($0.rawValue) }) else { return }
        if let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiff), let png = bitmap.representation(using: .png, properties: [:]) {
            add(Clip(kind: .image, data: png))
        } else if let value = pasteboard.string(forType: .string), let data = value.data(using: .utf8) {
            add(Clip(kind: .text, data: data))
        }
    }
    func select(_ clip: Clip) {
        pasteboard.clearContents()
        switch clip.kind {
        case .text: if let text = String(data: clip.data, encoding: .utf8) { pasteboard.setString(text, forType: .string) }
        case .image: if let image = NSImage(data: clip.data) { pasteboard.writeObjects([image]) }
        }
        changeCount = pasteboard.changeCount
        add(clip)
    }
    func remove(_ id: UUID) { history.remove(id); save() }
    func clear() { history.clear(); save() }
    private func add(_ clip: Clip) { history.add(clip); save() }
    private func save() {
        do {
            try FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            let data = try JSONEncoder().encode(history)
            try data.write(to: fileURL, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
        } catch { NSLog("NotchClip: failed to save history: %@", error.localizedDescription) }
    }
}
